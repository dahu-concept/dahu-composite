<?php
/**
 * “Dahu Kit” product type (dahu_kit).
 *
 * The container product carries NO price of its own: the price of a kit is the
 * sum of the selected components, computed server side by
 * Dahu_Composite_Engine (see also the cart / order rows: container at 0, one
 * child per component at the price of its product). We therefore store
 * _price = 0 so that WooCommerce considers the product purchasable, and we
 * hide the “shop” price (the equivalent of the WCCP “hidden” mode used on the
 * original kits).
 *
 * @package Dahu_Composite
 */

defined( 'ABSPATH' ) || exit;

class WC_Product_Dahu_Kit extends WC_Product {

	/**
	 * Configuration supplied on the fly, short-circuiting the database read.
	 *
	 * Used by the simulator of the administration screen: it must be able to
	 * test a configuration being entered, not saved yet. No other part of the
	 * plugin sets it — the public front end always goes through the metas.
	 *
	 * @var array|null ['components' => array, 'scenarios' => array, 'exceptions' => array|null]
	 */
	protected $kit_config_override = null;

	/**
	 * Generated scenarios, computed once per object: the engine evaluates the
	 * scenarios many times per request (projection).
	 *
	 * @var array|null
	 */
	protected $generated_scenarios = null;

	/**
	 * @return string
	 */
	public function get_type() {
		return DAHU_COMPOSITE_PRODUCT_TYPE;
	}

	/**
	 * Replaces the configuration read from the database with the supplied one.
	 * The arrays must already be normalised (Dahu_Composite_Kit_Config::sanitize_*).
	 *
	 * @param array      $components Normalised components.
	 * @param array      $scenarios  Normalised scenarios.
	 * @param array|null $exceptions Normalised customer exceptions; null = the
	 *                               saved ones.
	 */
	public function set_kit_config( array $components, array $scenarios, $exceptions = null ) {
		$this->kit_config_override = array(
			'components' => $components,
			'scenarios'  => $scenarios,
			'exceptions' => is_array( $exceptions ) ? $exceptions : null,
		);
		$this->generated_scenarios = null;
	}

	/**
	 * @return bool
	 */
	public function has_kit_config_override() {
		return null !== $this->kit_config_override;
	}

	/**
	 * Components of the kit (ordered array, already normalised).
	 *
	 * @return array
	 */
	public function get_kit_components() {
		if ( null !== $this->kit_config_override ) {
			return $this->kit_config_override['components'];
		}
		return Dahu_Composite_Kit_Config::get_components( $this->get_id() );
	}

	/**
	 * EFFECTIVE scenarios of the kit: the saved ones, then those generated by
	 * the public visibility and the customer exceptions. That is what the engine
	 * evaluates everywhere (hiding, validation, cart, projection).
	 *
	 * @return array
	 */
	public function get_kit_scenarios() {
		return array_merge( $this->get_kit_manual_scenarios(), $this->get_kit_generated_scenarios() );
	}

	/**
	 * SAVED scenarios (already normalised), without the generated scenarios.
	 *
	 * @return array
	 */
	public function get_kit_manual_scenarios() {
		if ( null !== $this->kit_config_override ) {
			return $this->kit_config_override['scenarios'];
		}
		return Dahu_Composite_Kit_Config::get_scenarios( $this->get_id() );
	}

	/**
	 * Customer exceptions, normalised.
	 *
	 * @return array
	 */
	public function get_kit_customer_exceptions() {
		if ( null !== $this->kit_config_override && is_array( $this->kit_config_override['exceptions'] ) ) {
			return $this->kit_config_override['exceptions'];
		}
		return Dahu_Composite_Customer_Access::get_exceptions( $this->get_id(), $this->get_kit_components() );
	}

	/**
	 * Generated scenarios: proposed variants
	 * (Dahu_Composite_Kit_Config::variation_scenarios()), then public visibility
	 * and exceptions (Dahu_Composite_Customer_Access::generated_scenarios()).
	 *
	 * @return array
	 */
	public function get_kit_generated_scenarios() {
		if ( null === $this->generated_scenarios ) {
			$components                = $this->get_kit_components();
			$this->generated_scenarios = array_merge(
				Dahu_Composite_Kit_Config::variation_scenarios( $components ),
				Dahu_Composite_Customer_Access::generated_scenarios( $components, $this->get_kit_customer_exceptions() )
			);
		}
		return $this->generated_scenarios;
	}

	/**
	 * Context in which the scenarios are evaluated: the current customer.
	 *
	 * @return array
	 */
	public function scenario_context() {
		return array( 'customer_id' => Dahu_Composite_Customer_Access::current_customer_id() );
	}

	/**
	 * Component by identifier.
	 *
	 * @param string $component_id Identifier of the component.
	 * @return array|null
	 */
	public function get_kit_component( $component_id ) {
		foreach ( $this->get_kit_components() as $component ) {
			if ( $component['id'] === $component_id ) {
				return $component;
			}
		}
		return null;
	}

	/**
	 * Evaluates the scenarios for a given selection state.
	 *
	 * @param array $selections [component_id => ['product_id' => int, 'variation_id' => int|null]].
	 * @return array ['hidden_components' => [...], 'hidden_options' => [component_id => [...]]]
	 */
	public function evaluate_scenarios( array $selections ) {
		return Dahu_Composite_Scenarios::evaluate( $this->get_kit_components(), $this->get_kit_scenarios(), $selections, $this->scenario_context() );
	}

	/**
	 * A kit is purchasable when it is published (or previewable) and has at
	 * least one component. The validity of the configuration is checked when it
	 * is added to the cart (Dahu_Composite_Engine::validate()).
	 *
	 * @return bool
	 */
	public function is_purchasable() {
		$purchasable = $this->exists()
			&& ( 'publish' === $this->get_status() || current_user_can( 'edit_post', $this->get_id() ) )
			&& ! empty( $this->get_kit_components() );

		return apply_filters( 'woocommerce_is_purchasable', $purchasable, $this );
	}

	/**
	 * The price of a kit depends on its configuration: no shop price.
	 *
	 * @param string $deprecated Unused.
	 * @return string
	 */
	public function get_price_html( $deprecated = '' ) {
		return apply_filters( 'dahu_composite_kit_price_html', '', $this );
	}

	/**
	 * @return string
	 */
	public function add_to_cart_text() {
		return apply_filters( 'woocommerce_product_add_to_cart_text', __( 'Configure', 'dahu-composite' ), $this );
	}

	/**
	 * @return string
	 */
	public function single_add_to_cart_text() {
		return apply_filters( 'woocommerce_product_single_add_to_cart_text', __( 'Add to cart', 'dahu-composite' ), $this );
	}

	/**
	 * From the product listings we point to the product page (configuration
	 * required), never a direct add to cart.
	 *
	 * @return string
	 */
	public function add_to_cart_url() {
		return apply_filters( 'woocommerce_product_add_to_cart_url', $this->get_permalink(), $this );
	}

	/**
	 * @param string $feature Feature.
	 * @return bool
	 */
	public function supports( $feature ) {
		if ( 'ajax_add_to_cart' === $feature ) {
			return false;
		}
		return parent::supports( $feature );
	}
}
