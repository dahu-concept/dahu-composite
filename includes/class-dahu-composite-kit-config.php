<?php
/**
 * Reading, normalising and writing the configuration of a kit.
 *
 * Product metadata (specific to the engine):
 *  - _dahu_kit_components: ordered array of components;
 *  - _dahu_kit_scenarios : array of scenarios.
 *
 * Format of a condition / masked-option value:
 *  - "123"      : the product 123, whatever its variation;
 *  - "123:456"  : only the variation 456 of the product 123;
 *  - "123:0"    : (conditions only) variable product 123 chosen but variation
 *                 not chosen yet — WCCP's "123_empty" key;
 *  - "none"     : (conditions only) no product selected in the source component
 *                 — reproduces WCCP's "0" key, used on the original kits (e.g.
 *                 “button hidden as long as no motor is chosen”);
 *  - "my-slug"  : option identifier of a “path” component (a choice with no
 *                 product: kit type, axle type, battery format).
 *
 * Scenario actions:
 *  - mask_component: removes the whole step;
 *  - mask_options  : removes options;
 *  - show_options  : shows ONLY the listed options (shown_options). Translated
 *                    on normalisation into masked_options = every other option
 *                    of the target component, variations included: the engine
 *                    evaluates it exactly like a mask_options;
 *  - block         : dead end — the configurator stops and shows a message (e.g.
 *                    front wheel + through axle). Such a scenario has no target
 *                    component; it carries a message and, optionally, the
 *                    component to offer as a restart point.
 *
 * @package Dahu_Composite
 */

defined( 'ABSPATH' ) || exit;

class Dahu_Composite_Kit_Config {

	const META_COMPONENTS = '_dahu_kit_components';
	const META_SCENARIOS  = '_dahu_kit_scenarios';

	/** Version of the JSON export/import format. */
	const EXPORT_VERSION = 1;

	/** Prefix of the scenarios generated by the “Proposed variants”. */
	const PREFIX_VARIATIONS = 'dahu-variations-';

	/** Option: data migrations already run. */
	const OPTION_MIGRATIONS = 'dahu_composite_migrations';

	/**
	 * Layouts of a multiple-choice component (the `display_style` key) — on top
	 * of '': the general appearance of the kit.
	 */
	const DISPLAY_STYLES = array( 'image', 'row', 'small', 'icon', 'chips' );

	/**
	 * @param int $product_id Kit product.
	 * @return array
	 */
	public static function get_components( $product_id ) {
		$raw = get_post_meta( $product_id, self::META_COMPONENTS, true );
		return is_array( $raw ) ? self::sanitize_components( $raw ) : array();
	}

	/**
	 * @param int $product_id Kit product.
	 * @return array
	 */
	public static function get_scenarios( $product_id ) {
		$raw = get_post_meta( $product_id, self::META_SCENARIOS, true );
		if ( ! is_array( $raw ) ) {
			return array();
		}
		$errors = array();
		return self::sanitize_scenarios( $raw, self::get_components( $product_id ), $errors );
	}

	/**
	 * Saves a complete configuration. Returns the list of normalisation warnings
	 * (items ignored or corrected).
	 *
	 * Customer exceptions: null = unchanged (import of a JSON that does not carry
	 * them — a configuration coming from staging does not wipe the exceptions of
	 * production); array = replaced.
	 *
	 * @param int        $product_id Kit product.
	 * @param array      $components Raw components.
	 * @param array      $scenarios  Raw scenarios.
	 * @param array|null $exceptions Raw customer exceptions, or null.
	 * @return string[]
	 */
	public static function save( $product_id, array $components, array $scenarios, $exceptions = null ) {
		$errors     = array();
		$components = self::sanitize_components( $components, $errors );
		$scenarios  = self::sanitize_scenarios( $scenarios, $components, $errors );

		update_post_meta( $product_id, self::META_COMPONENTS, $components );
		update_post_meta( $product_id, self::META_SCENARIOS, $scenarios );

		if ( is_array( $exceptions ) ) {
			update_post_meta( $product_id, Dahu_Composite_Customer_Access::META_EXCEPTIONS, Dahu_Composite_Customer_Access::sanitize_exceptions( $exceptions, $components, $errors ) );
		}

		return $errors;
	}

	/**
	 * Customer exceptions of a kit, normalised.
	 *
	 * @param int $product_id Kit product.
	 * @return array
	 */
	public static function get_customer_exceptions( $product_id ) {
		return Dahu_Composite_Customer_Access::get_exceptions( $product_id, self::get_components( $product_id ) );
	}

	/**
	 * JSON export (the same format as the import).
	 *
	 * @param int $product_id Kit product.
	 * @return array
	 */
	public static function export( $product_id ) {
		return array(
			'version'    => self::EXPORT_VERSION,
			'source'     => get_the_title( $product_id ) . ' #' . $product_id,
			'components' => self::get_components( $product_id ),
			'scenarios'  => self::get_scenarios( $product_id ),
			// User IDs: specific to the site. An import on another site
			// takes them as they are (the validator reports the unknown ones).
			'customer_exceptions' => self::get_customer_exceptions( $product_id ),
		);
	}

	/**
	 * Display checkbox of an option (show_image, show_description, show_specs,
	 * show_bundled).
	 *
	 * Absent = true, explicit = honoured. A test of the EXISTENCE of the key
	 * (array_key_exists), not isset(): a key present but null (JSON written by
	 * hand — the admin only writes booleans) is an explicit value, read as false,
	 * and not confused with an absent key.
	 *
	 * @param array  $option Raw option.
	 * @param string $key    Key of the checkbox.
	 * @return bool
	 */
	public static function display_flag( array $option, $key ) {
		return array_key_exists( $key, $option ) ? ! empty( $option[ $key ] ) : true;
	}

	/**
	 * Layout of a multiple-choice component: `display_style`, failing that the
	 * older test setting `test_display_style` of a configuration saved earlier.
	 * Unknown value: ''.
	 *
	 * @param array $component Component (raw or saved).
	 * @return string '' or one of DISPLAY_STYLES.
	 */
	public static function display_style( array $component ) {
		$style = isset( $component['display_style'] )
			? $component['display_style']
			: ( isset( $component['test_display_style'] ) ? $component['test_display_style'] : '' );
		return in_array( $style, self::DISPLAY_STYLES, true ) ? $style : '';
	}

	/**
	 * Normalises the list of components.
	 *
	 * @param array    $raw    Raw components.
	 * @param string[] $errors Warnings (by reference).
	 * @return array
	 */
	public static function sanitize_components( array $raw, array &$errors = array() ) {
		$components = array();
		$seen_ids   = array();
		$position   = 0;

		foreach ( $raw as $item ) {
			if ( ! is_array( $item ) ) {
				continue;
			}
			$position++;

			$title = isset( $item['title'] ) ? sanitize_text_field( (string) $item['title'] ) : '';
			$id    = isset( $item['id'] ) ? sanitize_title( (string) $item['id'] ) : '';
			if ( '' === $id ) {
				$id = '' !== $title ? sanitize_title( $title ) : 'composant-' . $position;
			}
			if ( isset( $seen_ids[ $id ] ) ) {
				$suffix = $position;
				while ( isset( $seen_ids[ $id . '-' . $suffix ] ) ) {
					$suffix++;
				}
				$new_id = $id . '-' . $suffix;
				/* translators: 1: duplicate identifier, 2: new identifier */
				$errors[] = sprintf( __( 'Duplicate component identifier “%1$s”: renamed “%2$s”.', 'dahu-composite' ), $id, $new_id );
				$id       = $new_id;
			}
			$seen_ids[ $id ] = true;

			// Type of component. 'product': the options are WooCommerce products
			// (the original behaviour, and the default value — existing
			// configurations do not have this field). 'path': a plain branch,
			// with no product, no price and no weight (kit type, axle type,
			// battery format). A 'path' component never produces a
			// cart row or an order row.
			$component_type = ( isset( $item['component_type'] ) && 'path' === $item['component_type'] ) ? 'path' : 'product';

			$options    = array();
			$option_ids = array();
			$raw_options = ( isset( $item['options'] ) && is_array( $item['options'] ) ) ? $item['options'] : array();

			if ( 'path' === $component_type ) {
				$n_option = 0;
				foreach ( $raw_options as $option ) {
					$option = is_array( $option ) ? $option : array( 'id' => $option );
					$n_option++;
					$label = isset( $option['label'] ) ? sanitize_text_field( (string) $option['label'] ) : '';
					$oid   = isset( $option['id'] ) ? sanitize_title( (string) $option['id'] ) : '';
					if ( '' === $oid ) {
						$oid = '' !== $label ? sanitize_title( $label ) : 'option-' . $n_option;
					}
					if ( isset( $option_ids[ $oid ] ) ) {
						continue;
					}
					$option_ids[ $oid ] = true;
					$options[]          = array(
						'id'                  => $oid,
						'label'               => '' !== $label ? $label : $oid,
						'display_description' => isset( $option['display_description'] ) && '' !== trim( (string) $option['display_description'] )
							? wp_kses_post( (string) $option['display_description'] ) : null,
						'display_image_id'    => ! empty( $option['display_image_id'] ) ? absint( $option['display_image_id'] ) : null,
						'badge'               => isset( $option['badge'] ) && '' !== trim( (string) $option['badge'] )
							? sanitize_text_field( (string) $option['badge'] ) : null,
						// Step with no sequel: the configurator stops and
						// shows “coming soon” (see the front end).
						'coming_soon'         => ! empty( $option['coming_soon'] ),
						// “link” card: not a choice, a pointer to
						// a page (contact, dealer map…). See
						// path_link().
						'link'                => self::path_link( $option ),
						// Identifier of a category of the component (see
						// normalize_tiers(), which resolves it after the loop).
						'tier'                => isset( $option['tier'] ) && '' !== trim( (string) $option['tier'] )
							? sanitize_text_field( (string) $option['tier'] ) : null,
					);
				}
			} else {
				foreach ( $raw_options as $option ) {
					$pid = is_array( $option ) ? ( isset( $option['product_id'] ) ? absint( $option['product_id'] ) : 0 ) : absint( $option );
					if ( $pid && ! isset( $option_ids[ $pid ] ) ) {
						$option_ids[ $pid ] = true;
						$option             = is_array( $option ) ? $option : array();

						// Display content specific to the kit. Every field is
						// optional: empty = the real data of the
						// product is shown (backward compatible with existing
						// configurations, which only have product_id).
						$options[] = array(
							'product_id'          => $pid,
							'display_title'       => isset( $option['display_title'] ) && '' !== trim( (string) $option['display_title'] )
								? sanitize_text_field( (string) $option['display_title'] ) : null,
							'display_description' => isset( $option['display_description'] ) && '' !== trim( (string) $option['display_description'] )
								? wp_kses_post( (string) $option['display_description'] ) : null,
							'display_image_id'    => ! empty( $option['display_image_id'] ) ? absint( $option['display_image_id'] ) : null,
							// “Help image”: a complementary image,
							// on the back of the card only (Description
							// section), at the top. The front image
							// (display_image_id, else the photo of the product) does not
							// depend on it. E.g. the measuring diagram of a rim.
							'help_image_id'       => ! empty( $option['help_image_id'] ) && absint( $option['help_image_id'] ) ? absint( $option['help_image_id'] ) : null,
							'badge'               => isset( $option['badge'] ) && '' !== trim( (string) $option['badge'] )
								? sanitize_text_field( (string) $option['badge'] ) : null,
							// Category (range) of the option: identifier
							// of an entry of the component's “tiers”, or
							// empty. Resolved by normalize_tiers().
							'tier'                => isset( $option['tier'] ) && '' !== trim( (string) $option['tier'] )
								? sanitize_text_field( (string) $option['tier'] ) : null,
							// Display of the card, checkboxes of the admin.
							// Rule: key ABSENT = true (an option
							// saved before these checkboxes existed: everything stays shown
							// as before); key PRESENT = value honoured.
							// The “specifications and included products off” defaults
							// of a NEW option are written explicitly
							// by the admin when it is created. Fields of the importable
							// JSON: reimporting a fixture replaces them.
							'show_image'          => self::display_flag( $option, 'show_image' ),
							'show_description'    => self::display_flag( $option, 'show_description' ),
							'show_specs'          => self::display_flag( $option, 'show_specs' ),
							'show_bundled'        => self::display_flag( $option, 'show_bundled' ),
							// Public visibility (see
							// Dahu_Composite_Customer_Access). The same rule as
							// the display checkboxes: key absent = public,
							// nothing changes on deployment. private_variations
							// = variations that are NOT public (empty: all of them
							// public), the equivalent of one is_public per
							// variation.
							'is_public'           => self::display_flag( $option, 'is_public' ),
							'private_variations'  => self::id_list( isset( $option['private_variations'] ) ? $option['private_variations'] : array() ),
							// Proposed variants: identifiers of the
							// variations OFFERED by this option, empty = all of them.
							// The others are hidden for everyone, always
							// (variation_scenarios(), a generated scenario).
							'allowed_variations'  => self::id_list( isset( $option['allowed_variations'] ) ? $option['allowed_variations'] : array() ),
							// Help image per variation:
							// { variation_id: attachment_id }. A variation
							// with no entry falls back to help_image_id.
							'variation_help_images' => self::id_map( isset( $option['variation_help_images'] ) ? $option['variation_help_images'] : array() ),
						);
					}
				}
			}

			$tiers = self::normalize_tiers( $item, $options );

			$qty_min = isset( $item['quantity_min'] ) ? max( 0, (int) $item['quantity_min'] ) : 1;

			$qty_max = isset( $item['quantity_max'] ) ? max( 0, (int) $item['quantity_max'] ) : $qty_min;
			if ( $qty_max < $qty_min ) {
				$qty_max = $qty_min;
			}
			// A mandatory component is ordered in quantity 1 at least.
			$optional = ! empty( $item['optional'] );
			if ( ! $optional && $qty_min < 1 ) {
				$qty_min = 1;
				$qty_max = max( 1, $qty_max );
			}

			// Adjustable quantity: unticked by default. Without the checkbox, the
			// customer chooses no quantity — one unit of the selected
			// option, that is all. The bounds are then brought back to 1 and the
			// quantity field is not shown on the product page.
			//
			// This default value applies to existing configurations TOO, which
			// do not have the field: the maxima inherited from WCCP
			// (99, 100) are no longer offered to the customer until the box is
			// ticked.
			$quantity_editable = ! empty( $item['quantity_editable'] );
			if ( ! $quantity_editable ) {
				// An optional component keeps its minimum at 0: that is what
				// makes it optional, not the quantity.
				$qty_min = $optional ? 0 : 1;
				$qty_max = 1;
			}

			// Selection mode: “radio” (one option, the default and
			// every existing configuration) or “multiple” (several
			// options together, one row per option). Any other value —
			// including the former “dropdown” — falls back to “radio”. A
			// branch is always “radio”.
			$selection_mode = ( 'path' !== $component_type && isset( $item['selection_mode'] ) && 'multiple' === $item['selection_mode'] ) ? 'multiple' : 'radio';
			if ( 'multiple' === $selection_mode ) {
				// One unit per chosen option: no adjustable quantity
				// (it would apply to every option at once). The minimum
				// only says whether the component is optional.
				$quantity_editable = false;
				$qty_min           = $optional ? 0 : 1;
				$qty_max           = 1;
			}

			$default        = 0;
			$default_option = null;

			if ( 'path' === $component_type ) {
				// A branch carries neither a quantity, nor shipping, nor a
				// default product: only a choice.
				$qty_min           = 1;
				$qty_max           = 1;
				$quantity_editable = false;
				$default_option = isset( $item['default_option_id'] ) ? sanitize_title( (string) $item['default_option_id'] ) : '';
				if ( '' === $default_option || ! isset( $option_ids[ $default_option ] ) ) {
					$default_option = null;
				}
			} else {
				$default = isset( $item['default_product_id'] ) ? absint( $item['default_product_id'] ) : 0;
				if ( $default && ! isset( $option_ids[ $default ] ) ) {
					/* translators: 1: product, 2: component */
					$errors[] = sprintf( __( 'Default product #%1$d is not among the options of component “%2$s”: ignored.', 'dahu-composite' ), $default, $title );
					$default  = 0;
				}
			}

			// Anchor: the component alone (next to the CHOSEN card
			// of that component), or the component and a precise card. A
			// card with no component is incomplete.
			$anchor_component = isset( $item['anchor_component_id'] ) ? sanitize_title( (string) $item['anchor_component_id'] ) : '';
			$anchor_product   = isset( $item['anchor_product_id'] ) ? absint( $item['anchor_product_id'] ) : 0;
			if ( '' === $anchor_component || 'path' === $component_type ) {
				if ( 'path' !== $component_type && $anchor_product ) {
					/* translators: %s: component */
					$errors[] = sprintf( __( '“%s”: incomplete anchoring (a card with no anchor component). It is shown in its usual place.', 'dahu-composite' ), '' !== $title ? $title : $id );
				}
				$anchor_component = null;
				$anchor_product   = null;
			} elseif ( ! $anchor_product ) {
				$anchor_product = null;
			}

			$components[] = array(
				'id'                   => $id,
				'component_type'       => $component_type,
				'title'                => $title,
				'description'          => isset( $item['description'] ) ? wp_kses_post( (string) $item['description'] ) : '',
				// Text of the info bubble of the step, optional:
				// an expandable panel under the header. An older configuration
				// without the key: an empty string, no bubble.
				'info'                 => isset( $item['info'] ) ? trim( wp_kses_post( (string) $item['info'] ) ) : '',
				// Image of the “None” card of THIS component, an attachment
				// from the media library, optional: it replaces the shared
				// image (Appearance panel) for this component only.
				// Of no object for a branch. An older configuration without
				// the key: null, the shared image.
				'none_image_id'        => ( 'path' !== $component_type && ! empty( $item['none_image_id'] ) && absint( $item['none_image_id'] ) ) ? absint( $item['none_image_id'] ) : null,
				// Components sharing the same value = the same screen of the
				// configurator. Purely visual: every component stays
				// validated and priced separately by the engine.
				'display_group'        => isset( $item['display_group'] ) ? sanitize_title( (string) $item['display_group'] ) : '',
				// Role of the title in a grouped screen: “primary” (default) =
				// the title of the component goes into that of the screen;
				// “secondary” = a supporting component (an add-on next to a
				// main choice): neither in the title of the screen, nor a title
				// of its own. Display only.
				'title_role'           => ( isset( $item['title_role'] ) && 'secondary' === $item['title_role'] ) ? 'secondary' : 'primary',
				// Anchor of an “add-on” component, optional: the
				// card next to which it is shown — a component of
				// the screen + the base product of the option (the card, not a
				// variant). Component alone, with no product: next to
				// the CHOSEN card of that component. Display only. A reference that
				// matches nothing is kept (the validator reports it, the
				// front end falls back to the usual place). An older
				// configuration without the keys: null, rendering unchanged.
				'anchor_component_id'  => $anchor_component,
				'anchor_product_id'    => $anchor_product,
				// Presentation of an “add-on” component: '' = a
				// “Select / Selected” card; 'question' = a yes / no question in the
				// chosen card of the anchor component (“Yes” chooses the single
				// option, “No” chooses nothing). Display only: the
				// selection, the scenarios, the prices and the cart are those of an
				// ordinary optional component. Kept as it is on a
				// component that is not (yet) an add-on: the front end ignores it,
				// the validator reports it. `question`: the text asked, empty =
				// the title of the component. An older configuration without the keys:
				// empty strings, rendering unchanged.
				'presentation'         => ( 'path' !== $component_type && 'multiple' !== $selection_mode && isset( $item['presentation'] ) && 'question' === $item['presentation'] ) ? 'question' : '',
				'question'             => ( 'path' !== $component_type && isset( $item['question'] ) ) ? sanitize_text_field( (string) $item['question'] ) : '',
				// “radio” or “multiple” (see above). The dropdown-list
				// mode has been removed: an older value
				// “dropdown” that was saved is read as “radio”.
				'selection_mode'       => $selection_mode,
				// Layout of a multiple-choice component: ''
				// = the general appearance of the kit (the usual “add-on” cards),
				// or one of DISPLAY_STYLES — 'image' (product card in a
				// grid), 'row' (expandable row), 'small', 'icon', 'chips'.
				// Set component by component; rendering only, see
				// displayStyle() on the front end. The older test setting
				// (`test_display_style`): read back as long as the new key
				// does not exist, then dropped when saving.
				'display_style'        => 'multiple' === $selection_mode ? self::display_style( $item ) : '',
				'quantity_min'         => $qty_min,
				'quantity_max'         => $qty_max,
				'quantity_editable'    => $quantity_editable,
				'default_product_id'   => $default ? $default : null,
				'default_option_id'    => $default_option,
				// Categories (ranges) of the component, in the order of the sections.
				'tiers'                => $tiers,
				// Display of the ranges, three independent settings,
				// disabled by default (the earlier rendering):
				//  - tier_newline: every range starts a new row of
				//    cards, instead of following the previous one on the same row;
				//  - tier_badge: name of the range as a pill to the right of the name
				//    of every card, on the colour of the range;
				//  - tier_tint: background of every card tinted with the colour of
				//    its range, very discreetly.
				// Badge: key ABSENT = ticked (a component never
				// saved with this setting, an import JSON that does not carry
				// it); key present = honoured.
				'tier_newline'         => ! empty( $tiers ) && ! empty( $item['tier_newline'] ),
				'tier_badge'           => ! empty( $tiers ) && ( ! array_key_exists( 'tier_badge', $item ) || ! empty( $item['tier_badge'] ) ),
				'tier_tint'            => ! empty( $tiers ) && ! empty( $item['tier_tint'] ),
				'options'              => $options,
				'shipped_individually' => ( 'path' === $component_type ) ? false : ! empty( $item['shipped_individually'] ),
				// DISPLAYED weight of the step, in grams: '' = weight of the
				// products (the default; a configuration saved before the key:
				// rendering unchanged), 'fixed' = weight_grams instead, 'subtract' =
				// weight of the products minus weight_grams, never below 0. Applied
				// once to the total of the step by the quote
				// (Dahu_Composite_Engine::quote()): never to the weight of the cart
				// rows or of the order rows (shipping, dahu-post).
				'weight_mode'          => ( 'path' !== $component_type && isset( $item['weight_mode'] ) && in_array( $item['weight_mode'], array( 'fixed', 'subtract' ), true ) ) ? $item['weight_mode'] : '',
				'weight_grams'         => ( 'path' !== $component_type && isset( $item['weight_grams'] ) && is_numeric( $item['weight_grams'] ) ) ? max( 0, (int) round( (float) $item['weight_grams'] ) ) : 0,
				'optional'             => $optional,
			);
		}

		return $components;
	}

	/**
	 * Categories (ranges) of a component: an ordered list
	 * [ { id, label, description, media_id, media_url } ] (media: see
	 * tier_media()), the order of the array being the order of the sections of
	 * the configurator. The “tier” field of an option references an id of this
	 * list (or is empty): renaming a category does not touch the options.
	 *
	 * Backward compatibility: an older saved configuration (or a JSON import in
	 * the older format) has no “tiers” key and carries a free label in “tier”.
	 * The categories are then created from the distinct values, in the order of
	 * their first appearance — which was already the order of the sections — and
	 * “tier” is replaced by the id. The same rendering as before, without saving
	 * anything: the migration happens on every read until the configuration is
	 * saved again from the metabox.
	 *
	 * An option that references an absent id keeps it (the validator reports it);
	 * a value equal to the LABEL of a category falls back to its id (JSON written
	 * by hand).
	 *
	 * @param array $item    Raw component.
	 * @param array $options Normalised options (by reference: “tier” is
	 *                       rewritten).
	 * @return array
	 */
	private static function normalize_tiers( array $item, array &$options ) {
		$tiers    = array();
		$by_id    = array();
		$by_label = array();

		// $media: media of the bubble of the range, see tier_media();
		// colour, see tier_color().
		$add = function ( $id, $label, $description, array $media = array() ) use ( &$tiers, &$by_id, &$by_label ) {
			$base = '' !== $id ? $id : sanitize_title( $label );
			if ( '' === $base ) {
				$base = 'categorie';
			}
			$id = $base;
			$n  = 2;
			while ( isset( $by_id[ $id ] ) ) {
				$id = $base . '-' . $n++;
			}
			$by_id[ $id ] = true;
			if ( ! isset( $by_label[ $label ] ) ) {
				$by_label[ $label ] = $id;
			}
			$tiers[] = array(
				'id'          => $id,
				'label'       => $label,
				'description' => $description,
				'media_id'    => isset( $media['media_id'] ) ? $media['media_id'] : null,
				'media_url'   => isset( $media['media_url'] ) ? $media['media_url'] : '',
				'color'       => isset( $media['color'] ) ? $media['color'] : '',
			);
			return $id;
		};

		if ( isset( $item['tiers'] ) && is_array( $item['tiers'] ) ) {
			foreach ( $item['tiers'] as $raw ) {
				if ( ! is_array( $raw ) ) {
					continue;
				}
				$label = isset( $raw['label'] ) ? sanitize_text_field( (string) $raw['label'] ) : '';
				$id    = isset( $raw['id'] ) ? sanitize_title( (string) $raw['id'] ) : '';
				if ( '' === $label && '' === $id ) {
					continue;
				}
				$description = isset( $raw['description'] ) && '' !== trim( (string) $raw['description'] )
					? wp_kses_post( (string) $raw['description'] ) : null;
				$add( $id, '' !== $label ? $label : $id, $description, array_merge( self::tier_media( $raw ), self::tier_color( $raw ) ) );
			}
			foreach ( $options as &$option ) {
				if ( null === $option['tier'] ) {
					continue;
				}
				$value = $option['tier'];
				$slug  = sanitize_title( $value );
				if ( isset( $by_id[ $slug ] ) ) {
					$option['tier'] = $slug;
				} elseif ( isset( $by_label[ $value ] ) ) {
					$option['tier'] = $by_label[ $value ];
				} else {
					$option['tier'] = '' !== $slug ? $slug : null;
				}
			}
			unset( $option );
			return $tiers;
		}

		// Older format: free labels on the options.
		foreach ( $options as &$option ) {
			if ( null === $option['tier'] ) {
				continue;
			}
			$label            = $option['tier'];
			$option['tier'] = isset( $by_label[ $label ] ) ? $by_label[ $label ] : $add( '', $label, null );
		}
		unset( $option );
		return $tiers;
	}

	/**
	 * Media of the popover of a range, on top of its text:
	 *  - media_id  : attachment from the media library, image or video; null
	 *                otherwise (an ID specific to the site, like display_image_id);
	 *  - media_url : link of a video (YouTube, Vimeo…: WordPress oEmbed
	 *                integration; or a .mp4 / .webm file), '' otherwise.
	 * The two may coexist: the attachment comes first (see
	 * Dahu_Composite_Engine::tier_media_html()). A configuration saved before
	 * this: keys absent, no media.
	 *
	 * @param array $raw Raw range.
	 * @return array ['media_id' => int|null, 'media_url' => string]
	 */
	private static function tier_media( array $raw ) {
		$id = isset( $raw['media_id'] ) ? absint( $raw['media_id'] ) : 0;
		return array(
			'media_id'  => $id ? $id : null,
			'media_url' => isset( $raw['media_url'] ) ? esc_url_raw( trim( (string) $raw['media_url'] ), array( 'http', 'https' ) ) : '',
		);
	}

	/**
	 * Link of a branch option: the card is then not a choice but a pointer to a
	 * page. Two forms accepted:
	 *  - a complete http(s) address (another site, an anchor…): esc_url_raw();
	 *  - a path or slug of a page of the site (“contact”, “/map/”): kept as it is,
	 *    cleaned, and resolved when read by home_url() (see
	 *    Dahu_Composite_Engine::path_link_url()) — the same kit works in
	 *    production and on a site installed in a subfolder (staging).
	 * '' = an ordinary option. An earlier configuration: key absent.
	 *
	 * @param array $option Raw option.
	 * @return string
	 */
	private static function path_link( array $option ) {
		$raw = isset( $option['link'] ) ? trim( (string) $option['link'] ) : '';
		if ( '' === $raw ) {
			return '';
		}
		if ( preg_match( '#^https?://#i', $raw ) ) {
			return esc_url_raw( $raw, array( 'http', 'https' ) );
		}
		// Path of the site: letters, digits, hyphens, slashes, underscores,
		// dots, and an optional query string or anchor.
		$path = preg_replace( '#[^A-Za-z0-9/_.\-?=&\#%]#', '', $raw );
		return '' === trim( $path, '/' ) ? '' : $path;
	}

	/**
	 * Colour of a range: “#rrggbb”, or '' = the default colour, assigned by the
	 * front end in the order of the ranges of the kit (the palette of
	 * DahuCompositeTiers.tierColor()). Used by the badge and the tinted background
	 * of the cards (the tier_badge / tier_tint settings of the component). An
	 * earlier configuration: key absent, the default colour.
	 *
	 * @param array $raw Raw range.
	 * @return array ['color' => string]
	 */
	private static function tier_color( array $raw ) {
		$color = isset( $raw['color'] ) ? sanitize_hex_color( trim( (string) $raw['color'] ) ) : '';
		// “#abc” is accepted by sanitize_hex_color(): brought back to “#aabbcc”.
		if ( $color && 4 === strlen( $color ) ) {
			$color = '#' . $color[1] . $color[1] . $color[2] . $color[2] . $color[3] . $color[3];
		}
		return array( 'color' => $color ? strtolower( $color ) : '' );
	}

	/**
	 * Normalises the list of scenarios.
	 *
	 * Rules:
	 *  - the target component must exist;
	 *  - a condition may only bear on a component placed BEFORE the target
	 *    component (descending cascade, as in WCCP) — the others are removed with
	 *    a warning;
	 *  - a mask_options scenario with no option to hide is ignored.
	 *
	 * @param array    $raw        Raw scenarios.
	 * @param array    $components Normalised components.
	 * @param string[] $errors     Warnings (by reference).
	 * @return array
	 */
	public static function sanitize_scenarios( array $raw, array $components, array &$errors = array() ) {
		$positions = array();
		foreach ( $components as $index => $component ) {
			$positions[ $component['id'] ] = $index;
		}

		$scenarios = array();
		$seen_ids  = array();
		$n         = 0;

		foreach ( $raw as $item ) {
			if ( ! is_array( $item ) ) {
				continue;
			}
			$n++;

			$id = isset( $item['id'] ) ? sanitize_title( (string) $item['id'] ) : '';
			// Prefixes of the GENERATED scenarios: reserved, a saved scenario
			// cannot carry them (it would be confused with them).
			if ( 0 === strpos( $id, Dahu_Composite_Customer_Access::PREFIX_PUBLIC ) || 0 === strpos( $id, Dahu_Composite_Customer_Access::PREFIX_EXCEPTION ) || 0 === strpos( $id, self::PREFIX_VARIATIONS ) ) {
				$id = 'manuel-' . $id;
			}
			if ( '' === $id || isset( $seen_ids[ $id ] ) ) {
				$id = ( '' === $id ? 'scenario' : $id ) . '-' . $n;
			}
			$seen_ids[ $id ] = true;

			$action = isset( $item['action'] ) ? (string) $item['action'] : '';
			if ( ! in_array( $action, array( 'mask_component', 'mask_options', 'show_options', 'block' ), true ) ) {
				$action = 'mask_options';
			}
			$target = isset( $item['target_component'] ) ? sanitize_title( (string) $item['target_component'] ) : '';

			// A “block” scenario has no target component: it applies
			// to the whole configuration. Its conditions are therefore evaluated
			// without any constraint of position in the cascade.
			$is_block = ( 'block' === $action );

			if ( ! $is_block && ! isset( $positions[ $target ] ) ) {
				/* translators: %s: identifier of the scenario */
				$errors[] = sprintf( __( 'Scenario “%s”: unknown target component; scenario ignored.', 'dahu-composite' ), $id );
				continue;
			}

			$conditions     = array();
			$raw_conditions = ( isset( $item['conditions'] ) && is_array( $item['conditions'] ) ) ? $item['conditions'] : array();
			foreach ( $raw_conditions as $source => $condition ) {
				$source = sanitize_title( (string) $source );
				if ( ! isset( $positions[ $source ] ) || ! is_array( $condition ) ) {
					continue;
				}
				if ( ! $is_block && $positions[ $source ] >= $positions[ $target ] ) {
					/* translators: 1: scenario, 2: source component */
					$errors[] = sprintf( __( 'Scenario “%1$s”: the condition on “%2$s” does not come before the target component; condition removed.', 'dahu-composite' ), $id, $source );
					continue;
				}
				$values = self::sanitize_values( isset( $condition['values'] ) ? $condition['values'] : array(), true );
				if ( empty( $values ) ) {
					continue;
				}
				$conditions[ $source ] = array(
					'mode'   => ( isset( $condition['mode'] ) && 'not_in' === $condition['mode'] ) ? 'not_in' : 'in',
					'values' => $values,
				);
			}

			// A scenario with no condition is always active. When it had some on
			// input but none survived the normalisation (empty values,
			// badly placed source), keeping it would hide for ALL
			// customers: we discard it.
			if ( ! empty( $raw_conditions ) && empty( $conditions ) ) {
				/* translators: %s: identifier of the scenario */
				$errors[] = sprintf( __( 'Scenario “%s”: no valid condition; scenario ignored.', 'dahu-composite' ), $id );
				continue;
			}

			// Customer condition: a dimension SEPARATE from the component
			// conditions, with no cascade constraint (the customer depends
			// on no step). Absent = the key is absent from the normalised scenario:
			// the existing scenarios stay identical to the byte.
			$customer = self::sanitize_customer_condition( $item );

			$message = isset( $item['message'] ) ? wp_kses_post( (string) $item['message'] ) : '';
			$restart = isset( $item['restart_component'] ) ? sanitize_title( (string) $item['restart_component'] ) : '';
			if ( '' !== $restart && ! isset( $positions[ $restart ] ) ) {
				$restart = '';
			}

			if ( $is_block ) {
				// Without a condition, a block would make the kit impossible to configure.
				if ( empty( $conditions ) && null === $customer ) {
					/* translators: %s: identifier of the scenario */
					$errors[] = sprintf( __( 'Scenario “%s”: a block with no condition would make the composite product impossible to configure; scenario ignored.', 'dahu-composite' ), $id );
					continue;
				}
				$block = array(
					'id'                => $id,
					'action'            => 'block',
					'target_component'  => '',
					'conditions'        => $conditions,
					'masked_options'    => array(),
					'message'           => $message,
					'restart_component' => $restart,
				);
				if ( null !== $customer ) {
					$block['customer'] = $customer;
				}
				$scenarios[] = $block;
				continue;
			}

			$masked = array();
			$shown  = null;
			if ( 'mask_options' === $action ) {
				$masked = self::sanitize_values( isset( $item['masked_options'] ) ? $item['masked_options'] : array(), false );
				if ( empty( $masked ) ) {
					/* translators: %s: identifier of the scenario */
					$errors[] = sprintf( __( 'Scenario “%s”: no option to hide; scenario ignored.', 'dahu-composite' ), $id );
					continue;
				}
			} elseif ( 'show_options' === $action ) {
				// “Show only”: the list that was entered is
				// kept as it is (shown_options, what the admin edits);
				// masked_options is its complement, recomputed on EVERY
				// read against the current options and variations of the
				// component — an option added later is therefore hidden
				// automatically, with nothing to re-enter. The masked_options of an
				// imported JSON are ignored.
				$shown = self::sanitize_values( isset( $item['shown_options'] ) ? $item['shown_options'] : array(), false );
				if ( empty( $shown ) ) {
					/* translators: %s: identifier of the scenario */
					$errors[] = sprintf( __( 'Scenario “%s”: no option to show; scenario ignored.', 'dahu-composite' ), $id );
					continue;
				}
				$masked = self::complement_values( $components[ $positions[ $target ] ], $shown );
			}

			$scenario = array(
				'id'                => $id,
				'action'            => $action,
				'target_component'  => $target,
				'conditions'        => $conditions,
				'masked_options'    => $masked,
				'message'           => '',
				'restart_component' => '',
			);
			// Key present for show_options only: the other scenarios
			// stay identical to the byte.
			if ( null !== $shown ) {
				$scenario['shown_options'] = $shown;
			}
			if ( null !== $customer ) {
				$scenario['customer'] = $customer;
			}
			$scenarios[] = $scenario;
		}

		return $scenarios;
	}

	/**
	 * Complement of a “show only” list, in the masked_options format: everything
	 * the component offers EXCEPT the list.
	 *
	 *  - branch: every option whose id is not listed;
	 *  - listed product ("123"): nothing hidden for it;
	 *  - product only some of whose variations are listed ("123:456"): its OTHER
	 *    variations are hidden, the product stays;
	 *  - product absent from the list: hidden as a whole ("123").
	 *
	 * @param array    $component Normalised target component.
	 * @param string[] $shown     Values to show (normalised).
	 * @return string[]
	 */
	private static function complement_values( array $component, array $shown ) {
		$shown_set = array_flip( $shown );
		$masked    = array();

		foreach ( $component['options'] as $option ) {
			if ( 'path' === $component['component_type'] ) {
				if ( ! isset( $shown_set[ (string) $option['id'] ] ) ) {
					$masked[] = (string) $option['id'];
				}
				continue;
			}
			$pid = (string) (int) $option['product_id'];
			if ( isset( $shown_set[ $pid ] ) ) {
				continue;
			}
			$listed = false;
			foreach ( $shown as $value ) {
				if ( 0 === strpos( $value, $pid . ':' ) ) {
					$listed = true;
					break;
				}
			}
			if ( ! $listed ) {
				$masked[] = $pid;
				continue;
			}
			foreach ( Dahu_Composite_Customer_Access::variation_ids( (int) $pid ) as $variation_id ) {
				if ( ! isset( $shown_set[ $pid . ':' . $variation_id ] ) ) {
					$masked[] = $pid . ':' . $variation_id;
				}
			}
		}

		return $masked;
	}

	/**
	 * List of positive integer identifiers, without duplicates, in order.
	 *
	 * @param mixed $raw Array (or a single value).
	 * @return int[]
	 */
	private static function id_list( $raw ) {
		$ids = array();
		foreach ( (array) $raw as $value ) {
			$id = absint( $value );
			if ( $id ) {
				$ids[ $id ] = $id;
			}
		}
		return array_values( $ids );
	}

	/**
	 * Table { identifier: identifier } of positive integers (help image per
	 * variation); incomplete pairs are ignored.
	 *
	 * @param mixed $raw Associative array.
	 * @return array<int,int>
	 */
	private static function id_map( $raw ) {
		$map = array();
		foreach ( is_array( $raw ) ? $raw : array() as $key => $value ) {
			$key   = absint( $key );
			$value = absint( $value );
			if ( $key && $value ) {
				$map[ $key ] = $value;
			}
		}
		return $map;
	}

	/**
	 * Scenarios generated by the “Proposed variants”: for every option that
	 * offers ONLY certain variations (`allowed_variations` not empty), an
	 * unconditional hiding of the others, for everyone. The same mechanism as the
	 * public visibility (Dahu_Composite_Customer_Access::generated_scenarios()):
	 * the schema does not publish them (the “from” price is recomputed), the list
	 * of the front end does not offer them, the server refuses them and a
	 * selection carrying one loses it. A product none of whose proposed variations
	 * still exists: the whole option is hidden.
	 *
	 * @param array $components Normalised components.
	 * @return array[]
	 */
	public static function variation_scenarios( array $components ) {
		$scenarios = array();
		foreach ( $components as $component ) {
			if ( 'path' === $component['component_type'] ) {
				continue;
			}
			$masked = array();
			foreach ( $component['options'] as $option ) {
				$allowed = isset( $option['allowed_variations'] ) ? array_map( 'absint', (array) $option['allowed_variations'] ) : array();
				if ( ! $allowed ) {
					continue;
				}
				$pid      = (int) $option['product_id'];
				$children = Dahu_Composite_Customer_Access::variation_ids( $pid );
				if ( ! $children ) {
					continue; // Simple product: nothing to restrict.
				}
				$others = array_diff( $children, $allowed );
				foreach ( $others as $vid ) {
					$masked[] = $pid . ':' . $vid;
				}
				if ( count( $others ) === count( $children ) ) {
					$masked[] = (string) $pid;
				}
			}
			if ( ! $masked ) {
				continue;
			}
			$scenarios[] = array(
				'id'                => self::PREFIX_VARIATIONS . $component['id'],
				'action'            => 'mask_options',
				'target_component'  => $component['id'],
				'conditions'        => array(),
				'masked_options'    => array_values( array_unique( $masked ) ),
				'message'           => '',
				'restart_component' => '',
				'generated'         => 'variations',
			);
		}
		return $scenarios;
	}

	/**
	 * Data migrations, once per site:
	 *  - `tier_badge_060`: “Badge” ticked on the components of the existing kits
	 *    that have ranges. The setting was unticked by default and the editor
	 *    wrote it explicitly: the new default value (key absent = ticked) would
	 *    not have reached them.
	 * The raw meta is read back and written again as it is; only the key changes.
	 */
	public static function maybe_migrate() {
		$done = get_option( self::OPTION_MIGRATIONS, array() );
		$done = is_array( $done ) ? $done : array();
		if ( ! empty( $done['tier_badge_060'] ) ) {
			return;
		}
		$ids = get_posts(
			array(
				'post_type'      => 'product',
				'post_status'    => 'any',
				'posts_per_page' => -1,
				'fields'         => 'ids',
				'meta_key'       => self::META_COMPONENTS, // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_key
			)
		);
		foreach ( $ids as $product_id ) {
			$raw = get_post_meta( $product_id, self::META_COMPONENTS, true );
			if ( ! is_array( $raw ) ) {
				continue;
			}
			$changed = false;
			foreach ( $raw as $index => $component ) {
				if ( is_array( $component ) && ! empty( $component['tiers'] ) && empty( $component['tier_badge'] ) ) {
					$raw[ $index ]['tier_badge'] = true;
					$changed                     = true;
				}
			}
			if ( $changed ) {
				update_post_meta( $product_id, self::META_COMPONENTS, $raw );
			}
		}
		$done['tier_badge_060'] = DAHU_COMPOSITE_VERSION;
		update_option( self::OPTION_MIGRATIONS, $done, true );
	}

	/**
	 * Customer condition of a scenario: { mode: in|not_in, ids: int[] } — the
	 * `customer` key, or the `customer_in` / `customer_not_in` shorthands (a list
	 * of user IDs). null = no customer condition. Evaluated by
	 * Dahu_Composite_Scenarios::is_active() against the current customer.
	 *
	 * @param array $item Raw scenario.
	 * @return array|null
	 */
	private static function sanitize_customer_condition( array $item ) {
		if ( isset( $item['customer'] ) && is_array( $item['customer'] ) ) {
			$mode = ( isset( $item['customer']['mode'] ) && 'not_in' === $item['customer']['mode'] ) ? 'not_in' : 'in';
			$ids  = self::id_list( isset( $item['customer']['ids'] ) ? $item['customer']['ids'] : array() );
		} elseif ( isset( $item['customer_in'] ) ) {
			$mode = 'in';
			$ids  = self::id_list( $item['customer_in'] );
		} elseif ( isset( $item['customer_not_in'] ) ) {
			$mode = 'not_in';
			$ids  = self::id_list( $item['customer_not_in'] );
		} else {
			return null;
		}
		sort( $ids );
		return $ids ? array( 'mode' => $mode, 'ids' => $ids ) : null;
	}

	/**
	 * Option values in the scenario format ("123", "123:456", branch slug),
	 * without "none". Public access for the customer exceptions.
	 *
	 * @param mixed $raw Raw values.
	 * @return string[]
	 */
	public static function sanitize_value_list( $raw ) {
		return self::sanitize_values( $raw, false );
	}

	/**
	 * @param mixed $raw        Raw values (array or comma-separated string).
	 * @param bool  $allow_none Allow the value "none".
	 * @return string[]
	 */
	private static function sanitize_values( $raw, $allow_none ) {
		if ( is_string( $raw ) ) {
			$raw = explode( ',', $raw );
		}
		$values = array();
		foreach ( (array) $raw as $value ) {
			$value = trim( (string) $value );
			if ( 'none' === $value ) {
				if ( $allow_none ) {
					$values[ $value ] = true;
				}
				continue;
			}
			if ( preg_match( '/^(\d+)(?::(\d+))?$/', $value, $m ) ) {
				$values[ isset( $m[2] ) ? absint( $m[1] ) . ':' . absint( $m[2] ) : (string) absint( $m[1] ) ] = true;
				continue;
			}
			// Option identifier of a “path” component (a slug, never
			// numeric: no collision possible with a product ID).
			$slug = sanitize_title( $value );
			if ( '' !== $slug ) {
				$values[ $slug ] = true;
			}
		}
		// Numeric keys ("123") become integers in PHP: we turn them
		// back into strings for consistent strict comparisons.
		return array_map( 'strval', array_keys( $values ) );
	}
